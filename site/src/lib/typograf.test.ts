import assert from 'node:assert/strict'
import { test } from 'node:test'
// @ts-expect-error TS5097: Node запускает .ts без сборки и требует расширение (как в lead.test.ts)
import { typograf } from './typograf.ts'

const show = (s: string) => s.replace(/\u00A0/g, '~').replace(/\u2060/g, '^')

test('тире держится за предыдущее слово, диапазон не рвётся', () => {
  assert.equal(
    show(typograf('Не просто сайт — платформа. Запуск в среднем за 2–2,5 недели.')),
    'Не~просто сайт~— платформа. Запуск в~среднем за~2–^2,5~недели.',
  )
})

test('тире в конце фрагмента (двухтоновый заголовок)', () => {
  assert.equal(show(typograf('Не просто сайт —')), 'Не~просто сайт~—')
})

test('подряд идущие короткие слова связаны каждое', () => {
  assert.equal(show(typograf('СДЭК, 1С и в том числе')), 'СДЭК, 1С и~в~том числе')
})

test('номер, разряды и число со словом', () => {
  assert.equal(show(typograf('№ 1043 за 24 часа, скидка 60 %')), '№~1043~за~24~часа, скидка 60~%')
  assert.equal(show(typograf('100–1 000 товаров')), '100–^1~000~товаров')
})

test('частицы ли, же, бы держатся за предыдущее слово', () => {
  assert.equal(show(typograf('Можно ли дорабатывать магазин?')), 'Можно~ли дорабатывать магазин?')
  assert.equal(show(typograf('Что же делать, если')), 'Что~же делать, если')
  assert.equal(show(typograf('Смогу ли я сам')), 'Смогу~ли я сам')
})

test('местоимения не привязываются к следующему слову', () => {
  assert.equal(show(typograf('Что вы получаете')), 'Что вы получаете')
  assert.equal(show(typograf('Мы свяжемся с вами')), 'Мы свяжемся с~вами')
})
