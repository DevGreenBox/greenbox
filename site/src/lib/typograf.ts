// Русский набор без висящих строк: тире не начинает строку, короткое слово не остаётся в конце
// строки (кроме местоимений «вы», «мы», «он»…: связка «вы получаете» в узкой колонке рвёт слово),
// число не отрывается от следующего слова, «2–2,5», «1 000» и «№ 1043» не рвутся.
// Применяйте к текстам из src/content при выводе: {typograf(copy.hero.subtitle)}.

const NBSP = '\u00A0'
/** WORD JOINER: запрещает перенос после тире внутри диапазона. */
const WJ = '\u2060'

export function typograf(text: string): string {
  return text
    .replace(/ ([—–])(?=\s|$)/g, `${NBSP}$1`)
    .replace(/(\d)([–-])(\d)/g, `$1$2${WJ}$3`)
    // Частицы «ли», «же», «бы» держатся за предыдущее слово («Можно ли»), а не за следующее.
    .replace(/ (ли|ль|же|ж|бы|б)(?=[\s,.!?:;…»)]|$)/gi, `${NBSP}$1`)
    .replace(/(?<=^|[\s(«„"])(?!(?:ли|ль|же|ж|бы|б|вы|мы|ты|он|я|их|им|ей) )([а-яёА-ЯЁa-zA-Z]{1,2}) /gi, `$1${NBSP}`)
    .replace(/(\d) (?=\d{3}\b|[а-яёА-ЯЁ%₽])/g, `$1${NBSP}`)
    .replace(/№ /g, `№${NBSP}`)
}
